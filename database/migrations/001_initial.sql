CREATE TABLE cx_users (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  username VARCHAR2(40 CHAR) NOT NULL,
  email VARCHAR2(254 CHAR) NOT NULL,
  password_hash VARCHAR2(100 CHAR) NOT NULL,
  first_name VARCHAR2(80 CHAR) NOT NULL,
  last_name VARCHAR2(80 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_users_username_uq UNIQUE (username),
  CONSTRAINT cx_users_email_uq UNIQUE (email)
);

CREATE TABLE cx_accounts (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES cx_users(id),
  currency VARCHAR2(3 CHAR) NOT NULL,
  balance_minor NUMBER(20,0) DEFAULT 0 NOT NULL,
  version NUMBER DEFAULT 0 NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_accounts_user_currency_uq UNIQUE (user_id, currency),
  CONSTRAINT cx_accounts_balance_ck CHECK (balance_minor >= 0)
);

CREATE TABLE cx_sessions (
  token_hash CHAR(64 CHAR) PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES cx_users(id) ON DELETE CASCADE,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX cx_sessions_exp_idx ON cx_sessions(expires_at);

CREATE TABLE cx_fx_quotes (
  id VARCHAR2(36 CHAR) PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES cx_users(id),
  from_currency VARCHAR2(3 CHAR) NOT NULL,
  to_currency VARCHAR2(3 CHAR) NOT NULL,
  from_amount_minor NUMBER(20,0) NOT NULL,
  to_amount_minor NUMBER(20,0) NOT NULL,
  rate NUMBER(20,8) NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  consumed_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_fx_quote_amount_ck CHECK (from_amount_minor > 0 AND to_amount_minor > 0)
);

CREATE TABLE cx_merchants (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100 CHAR) NOT NULL,
  category VARCHAR2(50 CHAR) NOT NULL,
  currency VARCHAR2(3 CHAR) DEFAULT 'USD' NOT NULL,
  country_code VARCHAR2(2 CHAR) NOT NULL,
  active CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
  CONSTRAINT cx_merchants_active_ck CHECK (active IN ('Y', 'N'))
);

CREATE TABLE cx_operations (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES cx_users(id),
  operation_type VARCHAR2(24 CHAR) NOT NULL,
  idempotency_key VARCHAR2(80 CHAR) NOT NULL,
  recipient_id NUMBER REFERENCES cx_users(id),
  merchant_id NUMBER REFERENCES cx_merchants(id),
  from_currency VARCHAR2(3 CHAR) NOT NULL,
  to_currency VARCHAR2(3 CHAR) NOT NULL,
  from_amount_minor NUMBER(20,0) NOT NULL,
  to_amount_minor NUMBER(20,0) NOT NULL,
  fx_rate NUMBER(20,8) DEFAULT 1 NOT NULL,
  status VARCHAR2(20 CHAR) DEFAULT 'completed' NOT NULL,
  description VARCHAR2(200 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_operations_idem_uq UNIQUE (user_id, idempotency_key),
  CONSTRAINT cx_operations_amount_ck CHECK (from_amount_minor > 0 AND to_amount_minor > 0),
  CONSTRAINT cx_operations_status_ck CHECK (status IN ('completed', 'failed'))
);
CREATE INDEX cx_operations_user_idx ON cx_operations(user_id, created_at DESC);
CREATE INDEX cx_operations_recipient_idx ON cx_operations(recipient_id, created_at DESC);

CREATE TABLE cx_ledger_entries (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  operation_id NUMBER NOT NULL REFERENCES cx_operations(id),
  account_id NUMBER REFERENCES cx_accounts(id),
  currency VARCHAR2(3 CHAR) NOT NULL,
  amount_minor NUMBER(20,0) NOT NULL,
  entry_type VARCHAR2(24 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_ledger_amount_ck CHECK (amount_minor <> 0)
);
CREATE INDEX cx_ledger_operation_idx ON cx_ledger_entries(operation_id);
CREATE INDEX cx_ledger_account_idx ON cx_ledger_entries(account_id, created_at DESC);

CREATE TABLE cx_payment_requests (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  requester_id NUMBER NOT NULL REFERENCES cx_users(id),
  payer_id NUMBER NOT NULL REFERENCES cx_users(id),
  amount_minor NUMBER(20,0) NOT NULL,
  currency VARCHAR2(3 CHAR) NOT NULL,
  note VARCHAR2(160 CHAR) DEFAULT '' NOT NULL,
  status VARCHAR2(16 CHAR) DEFAULT 'pending' NOT NULL,
  operation_id NUMBER REFERENCES cx_operations(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  resolved_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT cx_requests_amount_ck CHECK (amount_minor > 0),
  CONSTRAINT cx_requests_status_ck CHECK (status IN ('pending', 'accepted', 'rejected'))
);
CREATE INDEX cx_requests_payer_idx ON cx_payment_requests(payer_id, status, created_at DESC);
CREATE INDEX cx_requests_requester_idx ON cx_payment_requests(requester_id, created_at DESC);

CREATE TABLE cx_splits (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  owner_id NUMBER NOT NULL REFERENCES cx_users(id),
  title VARCHAR2(100 CHAR) NOT NULL,
  total_minor NUMBER(20,0) NOT NULL,
  currency VARCHAR2(3 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_splits_total_ck CHECK (total_minor > 0)
);
CREATE TABLE cx_split_participants (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  split_id NUMBER NOT NULL REFERENCES cx_splits(id) ON DELETE CASCADE,
  user_id NUMBER NOT NULL REFERENCES cx_users(id),
  share_minor NUMBER(20,0) NOT NULL,
  request_id NUMBER REFERENCES cx_payment_requests(id),
  CONSTRAINT cx_split_participant_uq UNIQUE (split_id, user_id),
  CONSTRAINT cx_split_share_ck CHECK (share_minor > 0)
);

CREATE TABLE cx_recurrences (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  owner_id NUMBER NOT NULL REFERENCES cx_users(id),
  recipient_id NUMBER NOT NULL REFERENCES cx_users(id),
  amount_minor NUMBER(20,0) NOT NULL,
  currency VARCHAR2(3 CHAR) NOT NULL,
  frequency VARCHAR2(12 CHAR) NOT NULL,
  status VARCHAR2(12 CHAR) DEFAULT 'active' NOT NULL,
  next_run_at TIMESTAMP WITH TIME ZONE NOT NULL,
  last_run_at TIMESTAMP WITH TIME ZONE,
  last_run_status VARCHAR2(12 CHAR),
  last_error VARCHAR2(200 CHAR),
  last_operation_id NUMBER REFERENCES cx_operations(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_recurrences_amount_ck CHECK (amount_minor > 0),
  CONSTRAINT cx_recurrences_frequency_ck CHECK (frequency IN ('weekly', 'monthly', 'quarterly')),
  CONSTRAINT cx_recurrences_status_ck CHECK (status IN ('active', 'paused', 'cancelled')),
  CONSTRAINT cx_recurrences_result_ck CHECK (last_run_status IS NULL OR last_run_status IN ('completed', 'failed'))
);
CREATE INDEX cx_recurrences_due_idx ON cx_recurrences(status, next_run_at);

