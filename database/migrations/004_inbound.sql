CREATE TABLE cx_inbound_transfers (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES cx_users(id),
  operation_id NUMBER NOT NULL REFERENCES cx_operations(id),
  external_reference VARCHAR2(80 CHAR) NOT NULL,
  request_hash CHAR(64 CHAR) NOT NULL,
  source_country VARCHAR2(2 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_inbound_transfers_user_ref_uq UNIQUE (user_id, external_reference),
  CONSTRAINT cx_inbound_transfers_country_ck CHECK (source_country IN ('US', 'CO', 'CR'))
);

CREATE INDEX cx_inbound_transfers_user_idx ON cx_inbound_transfers(user_id, created_at DESC);
