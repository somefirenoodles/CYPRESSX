CREATE TABLE cx_ledger_journals (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  operation_id NUMBER NOT NULL REFERENCES cx_operations(id),
  request_hash CHAR(64 CHAR) NOT NULL,
  status VARCHAR2(10 CHAR) DEFAULT 'draft' NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_journals_operation_uq UNIQUE (operation_id),
  CONSTRAINT cx_journals_pair_uq UNIQUE (id, operation_id),
  CONSTRAINT cx_journals_status_ck CHECK (status IN ('draft', 'posted'))
);

