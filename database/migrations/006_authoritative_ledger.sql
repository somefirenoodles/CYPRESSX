/

CREATE OR REPLACE TRIGGER cx_journals_immutable
BEFORE UPDATE OR DELETE ON cx_ledger_journals FOR EACH ROW
DECLARE
  invalid_currencies NUMBER;
  entry_count NUMBER;
BEGIN
  IF DELETING THEN
    RAISE_APPLICATION_ERROR(-20001, 'El diario contable es inmutable.');
  END IF;
  IF :OLD.status <> 'draft' OR :NEW.status <> 'posted' OR :OLD.id <> :NEW.id
    OR :OLD.operation_id <> :NEW.operation_id OR :OLD.request_hash <> :NEW.request_hash
    OR :OLD.created_at <> :NEW.created_at THEN
    RAISE_APPLICATION_ERROR(-20001, 'Solo se permite contabilizar una vez.');
  END IF;
  SELECT COUNT(*) INTO entry_count FROM cx_ledger_entries WHERE journal_id = :OLD.id;
  SELECT COUNT(*) INTO invalid_currencies FROM
    (SELECT currency FROM cx_ledger_entries WHERE journal_id = :OLD.id GROUP BY currency HAVING SUM(amount_minor) <> 0);
  IF entry_count < 2 OR invalid_currencies <> 0 THEN
    RAISE_APPLICATION_ERROR(-20002, 'El asiento debe cuadrar por moneda y contener al menos dos partidas.');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER cx_journals_start_draft
BEFORE INSERT ON cx_ledger_journals FOR EACH ROW
BEGIN
  IF :NEW.status <> 'draft' THEN
    RAISE_APPLICATION_ERROR(-20001, 'El asiento debe crearse antes de contabilizarse.');
  END IF;
END;
/

