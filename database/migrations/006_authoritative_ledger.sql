CREATE OR REPLACE TRIGGER cx_entries_append_guard
BEFORE INSERT ON cx_ledger_entries FOR EACH ROW
DECLARE
  journal_status VARCHAR2(10);
BEGIN
  SELECT status INTO journal_status FROM cx_ledger_journals WHERE id = :NEW.journal_id FOR UPDATE;
  IF journal_status <> 'draft' THEN
    RAISE_APPLICATION_ERROR(-20001, 'No se admiten partidas en un asiento contabilizado.');
  END IF;
END;
/

CREATE OR REPLACE TRIGGER cx_entries_immutable
