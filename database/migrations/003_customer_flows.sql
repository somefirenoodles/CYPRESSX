CREATE TABLE cx_contacts (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  owner_id NUMBER NOT NULL REFERENCES cx_users(id),
  contact_id NUMBER NOT NULL REFERENCES cx_users(id),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_contacts_owner_contact_uq UNIQUE (owner_id, contact_id),
  CONSTRAINT cx_contacts_no_self_ck CHECK (owner_id <> contact_id)
);

CREATE INDEX cx_contacts_owner_idx ON cx_contacts(owner_id);

CREATE TABLE cx_bank_accounts (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  owner_id NUMBER NOT NULL REFERENCES cx_users(id),
  bank_name VARCHAR2(100 CHAR) NOT NULL,
  last4 VARCHAR2(4 CHAR) NOT NULL,
  fingerprint CHAR(64 CHAR) NOT NULL,
  status VARCHAR2(12 CHAR) DEFAULT 'active' NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_bank_accounts_owner_fp_uq UNIQUE (owner_id, fingerprint),
  CONSTRAINT cx_bank_accounts_status_ck CHECK (status IN ('active', 'disabled')),
  CONSTRAINT cx_bank_accounts_last4_ck CHECK (REGEXP_LIKE(last4, '^[0-9]{4}$'))
);

CREATE INDEX cx_bank_accounts_owner_idx ON cx_bank_accounts(owner_id);

CREATE TABLE cx_notifications (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  recipient_id NUMBER NOT NULL REFERENCES cx_users(id),
  event_key VARCHAR2(80 CHAR) NOT NULL,
  title VARCHAR2(120 CHAR) NOT NULL,
  message VARCHAR2(500 CHAR) NOT NULL,
  reference_type VARCHAR2(32 CHAR),
  reference_id NUMBER,
  read_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_notifications_user_event_uq UNIQUE (recipient_id, event_key)
);

CREATE INDEX cx_notifications_recipient_idx ON cx_notifications(recipient_id, created_at DESC);

CREATE INDEX cx_notifications_unread_idx ON cx_notifications(recipient_id, read_at);
