CREATE TABLE cx_idempotency_records (
  status VARCHAR2(10 CHAR) DEFAULT 'pending' NOT NULL CHECK (status IN ('pending', 'complete')),
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_id NUMBER NOT NULL REFERENCES cx_users(id) ON DELETE CASCADE,
  scope_name VARCHAR2(40 CHAR) NOT NULL,
  idempotency_key VARCHAR2(80 CHAR) NOT NULL,
  request_hash CHAR(64 CHAR) NOT NULL,
  response_json VARCHAR2(4000 CHAR) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT cx_idempotency_user_scope_key_uq UNIQUE (user_id, scope_name, idempotency_key),
  CONSTRAINT cx_idempotency_key_len_ck CHECK (LENGTH(idempotency_key) BETWEEN 8 AND 80)
);
CREATE INDEX cx_idempotency_user_idx ON cx_idempotency_records(user_id, created_at DESC);
